def main():
    HISTORY_DIR.mkdir(parents=True, exist_ok=True)

    metadata_dict = {item["resource_id"]: item for item in FLEET_METADATA}

    for resource_id, fn in STORY_SERVERS.items():
        df = generate_timeseries(resource_id, fn)
        df.to_csv(HISTORY_DIR / f"{resource_id}_history.csv", index=False)

        # Also write mapped fleet ID
        mapped_id = ID_MAP.get(resource_id)
        if mapped_id:
            df_mapped = df.copy()
            df_mapped["resource_id"] = mapped_id
            df_mapped.to_csv(HISTORY_DIR / f"{mapped_id}_history.csv", index=False)
            mapped_meta = dict(metadata_dict[resource_id])
            mapped_meta["resource_id"] = mapped_id
            metadata_dict[mapped_id] = mapped_meta

        print(f"[story]  {resource_id:15s} avg_cpu={df.cpu_percent.mean():5.1f}%  "
              f"p95={df.cpu_percent.quantile(0.95):5.1f}%  max={df.cpu_percent.max():5.1f}%")

    for spec in REMAINING_SPECS:
        fn = make_random_profile(spec["base_cpu"], spec["base_mem"], spec["gpu"], spec["profile"])
        df = generate_timeseries(spec["resource_id"], fn)
        df.to_csv(HISTORY_DIR / f"{spec['resource_id']}_history.csv", index=False)

        mapped_id = ID_MAP.get(spec["resource_id"])
        if mapped_id:
            df_mapped = df.copy()
            df_mapped["resource_id"] = mapped_id
            df_mapped.to_csv(HISTORY_DIR / f"{mapped_id}_history.csv", index=False)
            mapped_meta = dict(metadata_dict[spec["resource_id"]])
            mapped_meta["resource_id"] = mapped_id
            metadata_dict[mapped_id] = mapped_meta

        print(f"[random] {spec['resource_id']:15s} avg_cpu={df.cpu_percent.mean():5.1f}%  "
              f"p95={df.cpu_percent.quantile(0.95):5.1f}%  profile={spec['profile']}")

    with open(DATA_DIR / "fleet_metadata.json", "w", encoding="utf-8") as f:
        json.dump(list(metadata_dict.values()), f, indent=2)

    print(f"\nDone. Generated history for all servers.")
    print(f"Metadata written to {DATA_DIR / 'fleet_metadata.json'}")


if __name__ == "__main__":
    main()
