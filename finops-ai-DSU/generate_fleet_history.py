def make_random_profile(base_cpu, base_mem, has_gpu, profile):
    def fn(day_idx, hour_of_day, weekday):
        noise_c = np.random.normal(0, 3)
        noise_m = np.random.normal(0, 3)

        if profile == "orphaned_storage":
            return 0, 0, 0, 0, 0, 0, 0

        if profile == "batch_job" and hour_of_day in (2, 3, 4):
            cpu = 55 + np.random.normal(0, 8)
            mem = 60 + np.random.normal(0, 6)
        elif profile == "unscheduled_nonprod":
            cpu = base_cpu + noise_c + (5 if 9 <= hour_of_day <= 17 else 0)
            mem = base_mem + noise_m
        else:
            cpu = base_cpu + noise_c
            mem = base_mem + noise_m

        gpu = (4 + np.random.normal(0, 1.5)) if has_gpu else 0
        net = 100 + np.random.normal(0, 30)
        req = 50 + np.random.normal(0, 15) if base_cpu > 20 else 0
        lat = 30 + np.random.normal(0, 5) if base_cpu > 20 else 0
        err = 0.1
        return cpu, mem, gpu, net, req, lat, err
    return fn


