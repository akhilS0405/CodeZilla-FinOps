DAYS = 14


def clip(x, lo=0, hi=100):
    return max(lo, min(hi, x))


def generate_timeseries(resource_id, hourly_fn, days=DAYS):
    records = []
    for h in range(days * 24):
        ts = START + timedelta(hours=h)
        day_idx = h // 24
        hour_of_day = h % 24
        weekday = ts.weekday()
        cpu, mem, gpu, net, req, lat, err = hourly_fn(day_idx, hour_of_day, weekday)
        records.append({
            "resource_id": resource_id,
            "timestamp": ts.isoformat() + "Z",
            "day_index": day_idx,
            "hour_of_day": hour_of_day,
            "weekday": weekday,
            "cpu_percent": round(clip(cpu), 2),
            "memory_percent": round(clip(mem), 2),
            "gpu_percent": round(clip(gpu), 2),
            "network_mb": round(max(0, net), 1),
            "request_count": max(0, int(req)),
            "latency_ms": round(max(0, lat), 1),
            "error_rate_percent": round(clip(err, 0, 100), 3),
            "running": True,
        })
    return pd.DataFrame(records)


