"""
generate_fleet_history.py
==========================
Generates 14 days of hourly telemetry for the full 18-server fleet.

Populates data/history/*.csv and data/fleet_metadata.json.
No network calls. Pure local Python.

Usage:
    python generate_fleet_history.py
"""

